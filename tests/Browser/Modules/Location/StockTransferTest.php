    public function testStockTransferEdit(){
        $this->testStockTransfer();
        $this->browse(function (Browser $browser){
            $browser->click('#DataTables_Table_0 > tbody > tr.odd > td:nth-child(6) > div > button')
                ->click('#DataTables_Table_0 > tbody > tr.odd > td:nth-child(6) > div > div > a:nth-child(2)')
                ->assertSee('Edit Transfer')
                ->click('#add_product > section > div > div > div:nth-child(2) > div > form > div.col-12.mt-20 > div > button')
                ->waitFor('.toast-message')
                ->assertSee('Product Updated To Transfer List Successfully');
        });
    }


    public function testDeleteTransfer (){
        $this->testStockTransfer();
        $this->browse(function(Browser $browser){
            $browser
                ->click('#DataTables_Table_0 > tbody > tr.odd > td:nth-child(6) > div > button')
                    ->click('#DataTables_Table_0 > tbody > tr > td:nth-child(6) > div > div > a.dropdown-item.edit_brand')
                ->whenAvailable('#confirm-delete', function ($modal) {
                    $modal->click('#delete_link');
                })->waitFor('.toast-message')
                ->assertSee('Product deleted from Transfer List');

        });
    }

    public function testApproveTransfer (){
        $this->testStockTransfer();
        $this->browse(function(Browser $browser){
            $browser
                ->click('#DataTables_Table_0 > tbody > tr.odd > td:nth-child(6) > div > button')
                    ->click('#DataTables_Table_0 > tbody > tr:nth-child(1) > td:nth-child(6) > div > div > a:nth-child(1)')
                ->whenAvailable('#confirm-approve', function ($modal) {
                    $modal->click('#approve_link');
                })->waitFor('.toast-message')
                ->assertSee('Stock Transfer Approve Successfully');

        });
    }

    public function testReceiveTransfer (){
        $this->testApproveTransfer();
        $this->browse(function(Browser $browser){
            $browser
                ->pause(3000)
                ->click('#DataTables_Table_0 > tbody > tr.odd > td:nth-child(6) > div > button')
                    ->click('#DataTables_Table_0 > tbody > tr:nth-child(1) > td:nth-child(6) > div > div > a:nth-child(1)')
                ->whenAvailable('#confirm-approve', function ($modal) {
                    $modal->click('#approve_link');
                })->waitFor('.toast-message')
                ->assertSee('Stock Received Successfully');

        });
    }

