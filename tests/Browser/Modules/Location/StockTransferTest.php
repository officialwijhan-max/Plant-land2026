    public function testVisitPageWithoutLogin(){
        $this->browse(function (Browser $browser) {
            $browser->visit('inventory/stock-transfer')
                ->assertPathIs('/login');
        });
    }


    public function testVisitPageWithLogin(){
        $this->browse(function (Browser $browser) {
            $browser->loginAs(1)
            ->visit('inventory/stock-transfer')
                ->assertSee('Stock Transfer');
        });
    }

    public function testStockTransfer(){

