    }

    public function testDeleteCategory (){
        $this->testCreateCategoryWithAllField();
        $this->browse(function(Browser $browser){
           $browser->visit('/product/category')
           ->click('#dropdownMenu2')
               ->click('#DataTables_Table_0 > tbody > tr > td:nth-child(7) > div > div > a:nth-child(2)')
               ->whenAvailable('#confirm-delete', function ($modal) {
                    $modal->click('#delete_link');
               })->waitFor('.toast-message')
               ->assertSee('Category Deleted Successfully');

        });
    }

    public function testDeleteSubCategory (){
        $this->testCreateSubCategory();
        $this->browse(function(Browser $browser){
           $browser->visit('/product/category')
           ->click('#dropdownMenu2')
               ->click('#DataTables_Table_0 > tbody > tr > td:nth-child(7) > div > div > a:nth-child(2)')
