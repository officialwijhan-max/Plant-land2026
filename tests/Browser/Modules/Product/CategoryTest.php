                    $modal->pause(3000)
                        ->type('name', $this->faker->name)
                        ->type('code', $this->faker->randomNumber(4))
                        ->type('description', $this->faker->paragraph)
                        ->click('#categoryEditForm > div > div:nth-child(6) > div > label.primary_checkbox.d-flex.mr-12 > span')
                        ->click('#update_save_button_parent');
                })
                ->waitFor('.toast-message')
                ->assertSeeIn('.toast-message', 'Category Updated Successfully');
