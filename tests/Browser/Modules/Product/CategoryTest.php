               ->click('#DataTables_Table_0 > tbody > tr.even > td:nth-child(7) > div > div > a:nth-child(2)')
               ->whenAvailable('#confirm-delete', function ($modal) {
                    $modal->click('#delete_link');
               })->waitFor('.toast-message')
               ->assertSee('Category Deleted Successfully');
        });
    }


}
