                })
                ->assertSeeIn('.toast-message', 'Category Updated Successfully');
        });
    }


    public function testEditSubcategoryToParentCategory(){
        $this->testCreateSubCategory();
        $this->browse(function (Browser $browser){
            $browser->visit('/product/category')
                ->click('#dropdownMenu2')
                ->click('#DataTables_Table_0 > tbody > tr:nth-child(1) > td:nth-child(7) > div > div > a.dropdown-item.edit_category')
